/** Pure publication contracts. No service credentials or network access here. */
import type {PortfolioProject,PublishedSnapshot} from '../models';
import {cleanSnapshot} from '../validation';

export const PUBLIC_MEDIA_BUCKET='portfolio-public';
export const PRIVATE_MEDIA_BUCKET='portfolio-drafts';
const UUID='[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}';
const FULL_UUID=new RegExp(`^${UUID}$`,'i');
const PATH_RE=new RegExp(`^${UUID}/${UUID}/${UUID}\\.(png|jpg|webp)$`,'i');
export const MAX_PUBLIC_IMAGES=24;
export const MAX_IMAGE_BYTES=5*1024*1024;
const EXTENSIONS:Record<string,string>={'image/png':'png','image/jpeg':'jpg','image/webp':'webp'};

export function publicationPath(portfolioId:string,batchId:string,assetId:string,mimeType:string):string {
  if (![portfolioId,batchId,assetId].every(x=>FULL_UUID.test(x)))throw Error('Invalid publication identifiers.');
  const ext=EXTENSIONS[mimeType];if(!ext)throw Error('Unsupported public image type.');
  return `${portfolioId.toLowerCase()}/${batchId.toLowerCase()}/${assetId.toLowerCase()}.${ext}`;
}
export function publicAssetUrl(projectUrl:string,path:unknown):string {
  if(typeof path!=='string'||!PATH_RE.test(path))return '';
  let url:URL;try{url=new URL(projectUrl);}catch{return '';}
  if(url.protocol!=='https:' && !(url.protocol==='http:'&&['localhost','127.0.0.1'].includes(url.hostname)))return '';
  if(url.username||url.password||url.search||url.hash) return '';
  return new URL(`/storage/v1/object/public/${PUBLIC_MEDIA_BUCKET}/${path}`,url.origin).href;
}
export function imageMagicMatches(bytes:Uint8Array,mime:string):boolean {
  if(bytes.byteLength<12||bytes.byteLength>MAX_IMAGE_BYTES)return false;
  if(mime==='image/png')return [137,80,78,71,13,10,26,10].every((n,i)=>bytes[i]===n);
  if(mime==='image/jpeg')return bytes[0]===255&&bytes[1]===216&&bytes[2]===255&&bytes[bytes.length-2]===255&&bytes[bytes.length-1]===217;
  if(mime==='image/webp')return String.fromCharCode(...bytes.slice(0,4))==='RIFF'&&String.fromCharCode(...bytes.slice(8,12))==='WEBP';
  return false;
}
/** Only namespaced, immutable paths generated by the publication pipeline become visitor URLs. */
export function hydratePublishedSnapshot(raw:unknown,supabaseUrl:string):PublishedSnapshot|null {
  const clean=cleanSnapshot(raw);
  if(!clean)return null;
  const input=raw as {projects?:Array<Record<string,unknown>>};
  const byId=new Map((input.projects||[]).filter(x=>x&&typeof x==='object').map(x=>[x.id,x]));
  const projects:PortfolioProject[]=clean.projects.map(p=>{
    const r=byId.get(p.id);
    const coverUrl=publicAssetUrl(supabaseUrl,r?.coverPath);
    const gallery=Array.isArray(r?.gallery)?r.gallery.slice(0,12).map(item=>{
      const a=item&&typeof item==='object'?item as Record<string,unknown>:{};
      return {url:publicAssetUrl(supabaseUrl,a.path),alt:typeof a.alt==='string'?a.alt.slice(0,180):'',caption:typeof a.caption==='string'?a.caption.slice(0,240):''};
    }).filter(a=>a.url):[];
    return {...p,coverUrl,gallery};
  });
  return {...clean,projects};
}
export function safeProjectPath(slug:unknown):string|null {
  return typeof slug==='string'&&/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)&&slug.length<=100?slug:null;
}
