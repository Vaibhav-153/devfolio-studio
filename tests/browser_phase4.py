from pathlib import Path
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[1]
HTML=(ROOT/'preview-phase4/index.html').read_text()
SHOTS=ROOT/'preview-phase4/screenshots';SHOTS.mkdir(exist_ok=True)
results=[]
def verify(name,predicate):
    ok=bool(predicate);results.append((name,ok));print(('PASS' if ok else 'FAIL')+': '+name)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox','--disable-dev-shm-usage'])
    page=browser.new_page(viewport={'width':1440,'height':940},device_scale_factor=1)
    errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
    page.set_content(HTML,wait_until='domcontentloaded');page.wait_for_timeout(250)
    verify('publishing center renders',page.locator('h1',has_text='Publish with confidence.').count()==1)
    verify('begins as private draft',page.locator('#publish-state').inner_text()=='Private / unpublished')
    page.screenshot(path=str(SHOTS/'publishing-desktop.png'))
    page.locator('#name').fill('Jordan Lee');page.locator('#headline').fill('I build accessible systems.')
    verify('draft updates preview', 'I build accessible systems.' in page.locator('#frame').get_attribute('srcdoc'))
    page.locator('#publish').click();page.wait_for_timeout(100)
    verify('first publish creates release v1',page.locator('#publish-state').inner_text()=='Website is live • v1')
    verify('release history records v1',page.locator('#history-list').get_by_text('Version 1').count()==1)
    page.locator('#headline').fill('A newer draft, not yet published.')
    page.locator('[data-view="draft"]').click()
    verify('draft is independent of published release','A newer draft' in page.locator('#frame').get_attribute('srcdoc'))
    page.locator('[data-view="live"]').click()
    verify('public release is unchanged after editing','A newer draft' not in page.locator('#frame').get_attribute('srcdoc'))
    page.locator('#publish').click();page.wait_for_timeout(100)
    verify('second publish creates version 2',page.locator('#publish-state').inner_text()=='Website is live • v2')
    page.locator('#history-list [data-restore="local-1"]').click();page.wait_for_timeout(100)
    verify('restoring v1 creates new version 3',page.locator('#publish-state').inner_text()=='Website is live • v3')
    verify('restored release displays previous content','I build accessible systems.' in page.locator('#frame').get_attribute('srcdoc'))
    page.locator('#unpublish').click();page.wait_for_timeout(100)
    verify('unpublish removes live website',page.locator('#publish-state').inner_text()=='Private / unpublished')
    verify('unpublish retains release history',page.locator('#history-list [data-restore]').count()==3)
    verify('unpublished preview does not expose former release','No public website' in page.locator('#frame').get_attribute('srcdoc'))
    page.locator('[data-width="mobile"]').click();page.locator('[data-view="draft"]').click()
    verify('mobile portfolio preview is responsive',page.locator('#frame').get_attribute('class').endswith('mobile'))
    page.set_viewport_size({'width':390,'height':844});page.wait_for_timeout(200)
    page.screenshot(path=str(SHOTS/'publishing-mobile.png'),full_page=True)
    verify('mobile dashboard has no horizontal overflow',page.evaluate('document.documentElement.scrollWidth<=innerWidth+3'))
    verify('no JavaScript errors',not errors)
    browser.close()
print(f'Browser checks: {sum(ok for _,ok in results)}/{len(results)} passed')
if not all(x[1] for x in results):raise SystemExit(1)
